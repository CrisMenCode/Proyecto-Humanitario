"""Contratos que necesita la aplicación. Los adaptadores los implementan."""

from contextlib import AbstractContextManager
from typing import Protocol
from ayuda.domain.rules import AnalysisRequested, Page


class ResourceRepository(Protocol):
    kind: str

    def get(self, resource_id: int) -> dict: ...
    def list(
        self, *, page: int, page_size: int, search: str, campaign: int | None
    ) -> Page: ...
    def create(self, data: dict) -> dict: ...
    def update(self, resource_id: int, data: dict) -> dict: ...
    def delete(self, resource_id: int) -> None: ...
    def touch_campaigns(self, campaign_ids: set[int]) -> None: ...


class UnitOfWork(Protocol):
    def __call__(self) -> AbstractContextManager: ...


class CampaignAnalyzer(Protocol):
    def analyze(self, snapshot: dict) -> dict: ...


class EventPublisher(Protocol):
    def publish(self, event: AnalysisRequested) -> None: ...


class AnalysisRepository(Protocol):
    def request(self, campaign_id: int) -> tuple[dict, bool]: ...
    def get(self, analysis_id: str) -> dict: ...
    def claim(self, analysis_id: str) -> dict | None: ...
    def complete(self, analysis_id: str, result: dict) -> None: ...
    def fail(self, analysis_id: str, message: str) -> None: ...
